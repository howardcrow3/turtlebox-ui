#!/usr/bin/env python3
"""Bundle the web layer for websites: dist/web-light.css = css/fonts.css + css/tokens-light.css + css/web.css,
and copy fonts/ to dist/fonts/. Sites copy dist/ as is. Run from the repo root after build-tokens.py:
python3 scripts/build-tokens.py && python3 scripts/build-web.py"""
import pathlib, shutil
root = pathlib.Path(__file__).resolve().parent.parent
dist = root / "dist"
dist.mkdir(exist_ok=True)
parts = ["fonts.css", "tokens-light.css", "web.css"]
head = "/* Turtlebox UI web layer, light mode. GENERATED by scripts/build-web.py from " + ", ".join(f"css/{p}" for p in parts) + ". Do not edit. */\n"
(dist / "web-light.css").write_text(head + "\n".join((root / "css" / p).read_text() for p in parts))
(dist / "fonts").mkdir(exist_ok=True)
for f in (root / "fonts").iterdir():
    shutil.copy(f, dist / "fonts" / f.name)
print("wrote dist/web-light.css and dist/fonts/")
